#!/usr/bin/env node
// Toolchain 1.1 compliance prune of a GHDL 6.0.0 library tree (Phase 5C, decisions L1/L2 of Phase 5B).
//
//   node scripts/toolchain/ghdl-prune.mjs --lib <.../lib/ghdl> --ghdl <ghdl executable of the same tree> [--check]
//   node scripts/toolchain/ghdl-prune.mjs --lib <.../lib/ghdl> --index-from <already pruned .../lib/ghdl>
//
// The second form is for the GHDL library copy inside the Apio oss-cad-suite package, an ahead-of-time LLVM build whose
// ghdl does not launch on current macOS (and which MIX-FPGA never runs): its index files are identical to the JIT build's
// (checked when assembling), so the index comes from the pruned JIT tree, the object files of the removed units are deleted
// and every other object file stays byte for byte as upstream built it.
//
// Removes, from the official GHDL release content (nothing else is touched):
//   * the VHDL-87 and VHDL-93 IEEE libraries (ieee/v87, ieee/v93, src/ieee): they contain the IEEE 1076.3-1995
//     numeric_bit / numeric_std sources ("may not be sold or distributed for profit") and their compiled forms;
//   * the VITAL-95 and VITAL-2000 packages (src/vital95, src/vital2000), whose licence is not established;
//   * the UPF package (src/upf), which carries no licence statement.
// VITAL-2000 and UPF are compiled into the 2008 and 2019 IEEE library indexes, so those two libraries are
// regenerated by GHDL itself with the upstream rules of libraries/Makefile.inc (GHDL 6.0.0), minus the two removed
// package groups. The regenerated index files keep the analysis timestamps of the upstream release for every source
// that is unchanged, so the result does not depend on when it is built. `--check` regenerates in a scratch copy and
// verifies the committed result is what GHDL writes (modulo timestamps).
//
// MIX-FPGA only ever runs GHDL with --std=08 (core/vhdl/ghdl/ghdl-provider.ts).
import { spawnSync } from 'node:child_process';
import { cpSync, existsSync, readFileSync, readdirSync, rmSync, writeFileSync, mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';

const argv = process.argv.slice(2);
const opt = (k) => { const i = argv.indexOf(k); return i >= 0 ? argv[i + 1] : undefined; };
const lib = resolve(opt('--lib') ?? '');
const indexFrom = opt('--index-from') ? resolve(opt('--index-from')) : undefined;
const ghdl = resolve(opt('--ghdl') ?? '');
const checkOnly = argv.includes('--check');
const fail = (m) => { console.error(`ghdl-prune: ${m}`); process.exit(1); };
if (!opt('--lib') || (!opt('--ghdl') && !indexFrom)) fail('usage: --lib <lib/ghdl> (--ghdl <ghdl executable> | --index-from <pruned lib/ghdl>) [--check]');
if (!existsSync(join(lib, 'src', 'ieee2008'))) fail(`${lib} is not a GHDL library tree`);

/** Directories and files removed (relative to lib/ghdl). */
export const REMOVE = ['ieee/v87', 'ieee/v93', 'src/ieee', 'src/vital95', 'src/vital2000', 'src/upf'];

// libraries/Makefile.inc of GHDL 6.0.0: IEEE08_BSRCS without $(UPF_SRCS); VITAL2000 and UPF are not analysed at all.
const IEEE08 = ['std_logic_1164', 'std_logic_1164-body', 'std_logic_textio', 'math_real', 'math_real-body', 'math_complex', 'math_complex-body', 'numeric_bit', 'numeric_bit-body', 'numeric_bit_unsigned', 'numeric_bit_unsigned-body', 'numeric_std', 'numeric_std-body', 'numeric_std_unsigned', 'numeric_std_unsigned-body', 'fixed_float_types', 'fixed_generic_pkg', 'fixed_generic_pkg-body', 'fixed_pkg', 'float_generic_pkg', 'float_generic_pkg-body', 'float_pkg', 'ieee_bit_context', 'ieee_std_context'].map((n) => `ieee2008/${n}.vhdl`);
const SYNOPSYS08 = ['synopsys/std_logic_arith.vhdl', 'synopsys/std_logic_unsigned.vhdl', 'synopsys/std_logic_signed.vhdl', 'synopsys/v08/std_logic_misc.vhdl', 'synopsys/v08/std_logic_misc-body.vhdl'];
const LIBS = { 8: { sources: IEEE08, synopsys: SYNOPSYS08 }, 19: { sources: IEEE08, synopsys: [] } };

function run(args, cwd) {
    // Only the operating system's folders (and, on Windows, the folder of ghdl itself for its own DLLs): no developer tools.
    const PATH = process.platform === 'win32' ? [dirname(ghdl), join(process.env.SystemRoot ?? 'C:\\Windows', 'System32')].join(';') : '/usr/bin:/bin';
    const r = spawnSync(ghdl, args, { cwd, encoding: 'utf8', env: { ...process.env, PATH } });
    if (r.status !== 0) fail(`ghdl ${args.join(' ')} (in ${cwd}) failed:\n${r.stdout}${r.stderr}`);
}

/** path + sha1 -> timestamp, read from an upstream index. */
function timestamps(cf) {
    const m = new Map();
    for (const l of cf.split('\n')) {
        const x = /^file \. "([^"]+)" "([0-9a-f]{40})" "([0-9.]+)":/.exec(l);
        if (x) m.set(`${x[1]} ${x[2]}`, x[3]);
    }
    return m;
}

function regenerate(root, std) {
    const dir = join(root, 'ieee', `v${std === 8 ? '08' : '19'}`);
    const cfName = `ieee-obj${std === 8 ? '08' : '19'}.cf`;
    const cf = join(dir, cfName);
    const keep = existsSync(cf) ? timestamps(readFileSync(cf, 'latin1')) : new Map();
    // LLVM builds keep one object file per unit next to the index; the JIT build has only the index.
    for (const f of readdirSync(dir)) if (f.endsWith('.o') || f === cfName) rmSync(join(dir, f));
    const flag = `--std=${std === 8 ? '08' : '19'}`;
    for (const s of LIBS[std].sources) run(['-a', flag, '-P../..', '--work=ieee', `../../src/${s}`], dir);
    for (const s of LIBS[std].synopsys) run(['-a', flag, '-P../..', '--work=ieee', '-fsynopsys', `../../src/${s}`], dir);
    // Keep the upstream release's analysis timestamps (same source bytes), so the index does not depend on the build time.
    const out = readFileSync(cf, 'latin1').split('\n').map((l) => {
        const x = /^(file \. "([^"]+)" "([0-9a-f]{40})" ")([0-9.]+)(":)(\r?)$/.exec(l);
        if (!x) return l;
        const t = keep.get(`${x[2]} ${x[3]}`);
        return t ? `${x[1]}${t}${x[5]}${x[6]}` : l;
    }).join('\n');
    writeFileSync(cf, out, 'latin1');
}

/** Object files (LLVM builds) of the units that are no longer in the 2008/2019 libraries. */
const REMOVED_OBJECTS = ['timing_b', 'timing_p', 'prmtvs_b', 'prmtvs_p', 'memory_b', 'memory_p', 'upf', 'upf-body'];

function adoptIndex(root, std) {
    const v = std === 8 ? '08' : '19';
    const cf = join(root, 'ieee', `v${v}`, `ieee-obj${v}.cf`);
    const keep = timestamps(readFileSync(cf, 'latin1'));
    const reference = readFileSync(join(indexFrom, 'ieee', `v${v}`, `ieee-obj${v}.cf`), 'latin1');
    // Every source named by the reference index must be the same bytes (same sha1) as the one this tree's index recorded.
    const out = reference.split('\n').map((l) => {
        const x = /^(file \. "([^"]+)" "([0-9a-f]{40})" ")([0-9.]+)(":)(\r?)$/.exec(l);
        if (!x) return l;
        const t = keep.get(`${x[2]} ${x[3]}`);
        if (!t) fail(`${x[2]} (sha1 ${x[3]}) is not in this tree's original index: the two GHDL libraries are not from the same sources`);
        return `${x[1]}${t}${x[5]}${x[6]}`;
    }).join('\n');
    writeFileSync(cf, out, 'latin1');
    for (const n of REMOVED_OBJECTS) rmSync(join(root, 'ieee', `v${v}`, `${n}.o`), { force: true });
}

function prune(root) {
    for (const r of REMOVE) rmSync(join(root, r), { recursive: true, force: true });
    if (indexFrom) {
        adoptIndex(root, 8);
        adoptIndex(root, 19);
    } else {
        regenerate(root, 8);
        regenerate(root, 19);
    }
}

function verifyNoRemovedContent(root) {
    const bad = [];
    for (const r of REMOVE) if (existsSync(join(root, r))) bad.push(`still present: ${r}`);
    for (const v of ['08', '19']) {
        const t = readFileSync(join(root, 'ieee', `v${v}`, `ieee-obj${v}.cf`), 'latin1');
        if (/vital|upf|v87|v93/i.test(t)) bad.push(`ieee-obj${v}.cf still references removed content`);
    }
    if (bad.length) fail(bad.join('\n'));
}

if (checkOnly && !indexFrom) {
    const scratch = mkdtempSync(join(tmpdir(), 'ghdl-prune-check-'));
    try {
        cpSync(lib, join(scratch, 'lib'), { recursive: true });
        // The committed tree must already be pruned; regenerating it again must give the same index files.
        for (const std of [8, 19]) {
            const v = std === 8 ? '08' : '19';
            const before = readFileSync(join(lib, 'ieee', `v${v}`, `ieee-obj${v}.cf`), 'latin1');
            regenerate(join(scratch, 'lib'), std);
            const after = readFileSync(join(scratch, 'lib', 'ieee', `v${v}`, `ieee-obj${v}.cf`), 'latin1');
            if (before !== after) fail(`ieee-obj${v}.cf differs from a fresh GHDL regeneration`);
        }
        verifyNoRemovedContent(lib);
        console.log('ghdl-prune: tree is pruned and its indexes equal a fresh GHDL regeneration');
    } finally {
        rmSync(scratch, { recursive: true, force: true });
    }
} else if (checkOnly) {
    fail('--check needs --ghdl');
} else {
    prune(lib);
    verifyNoRemovedContent(lib);
    console.log(`ghdl-prune: pruned and regenerated ${lib}`);
}
