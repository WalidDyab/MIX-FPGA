#!/usr/bin/env node
// Builds "MIX-FPGA-<version>-Windows-x64-Setup.exe" (Windows Forms, installer/windows) with what every Windows PC already has: the
// .NET Framework C# compiler and Windows PowerShell for the icon. No SDK, no downloads, no packaging tool.
//
//   node scripts/installer/build-installer-windows.mjs [--vsix <file>] [--out <folder>]
//
// The installer contains no release files. It finds them next to itself, and it only accepts the exact files of this release: their
// sizes and SHA-256 values (the VSIX, the Nexys A7 support, the DE10-Lite support) are built INTO the executable from the committed pins
// (toolchains/mixfpga/payloads-1.1-windows-x64.json) and from the VSIX it is built with. The Setup code that installs the board support is
// the code inside the installed extension (bridge.js is only a thin caller); the installer never touches Altera, drivers or VS Code settings.
// Unsigned: no certificate is used and no security setting is changed.
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(fileURLToPath(new URL('../..', import.meta.url)));
const argv = process.argv.slice(2);
const opt = (k, d) => (argv.includes(k) ? resolve(argv[argv.indexOf(k) + 1]) : d);
const fail = (m) => { console.error(`installer build failed: ${m}`); process.exit(1); };
if (process.platform !== 'win32') fail('this builds the Windows installer');

const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const V = pkg.version;
const out = opt('--out', join(root, '.artifacts', 'installer-windows'));
const vsix = opt('--vsix', join(root, '.artifacts', 'dist', `nexysvhdl-${V}-win32-x64.vsix`));
if (!existsSync(vsix)) fail(`${vsix} is missing (node scripts/package.mjs --target win32-x64 --skip-zip)`);
const pins = JSON.parse(readFileSync(join(root, 'toolchains', 'mixfpga', 'payloads-1.1-windows-x64.json'), 'utf8')).payloads;
const sha = (f) => createHash('sha256').update(readFileSync(f)).digest('hex');

const obj = join(out, 'obj');
rmSync(out, { recursive: true, force: true });
mkdirSync(obj, { recursive: true });

// the Roslyn compiler of the Visual Studio Build Tools when present, else the compiler that ships with Windows (C# 5: the sources are C# 5)
const csc = join(process.env.WINDIR ?? 'C:\\Windows', 'Microsoft.NET', 'Framework64', 'v4.0.30319', 'csc.exe');
if (!existsSync(csc)) fail(`the .NET Framework C# compiler is missing: ${csc}`);
const run = (exe, args) => {
    const r = spawnSync(exe, args, { encoding: 'utf8' });
    if (r.status !== 0) fail(`${exe} ${args.join(' ')}\n${r.stdout}${r.stderr}`);
    return r;
};

// ---- pins built into the executable
const row = (name, f) => `        new PinInfo("${name}", ${statSync(f).size}L, "${sha(f)}")`;
const rows = [
    row(`nexysvhdl-${V}-win32-x64.vsix`, vsix),
    `        new PinInfo("${pins['nexys-a7-100t'].file}", ${pins['nexys-a7-100t'].bytes}L, "${pins['nexys-a7-100t'].sha256}")`,
    `        new PinInfo("${pins['de10-lite'].file}", ${pins['de10-lite'].bytes}L, "${pins['de10-lite'].sha256}")`,
];
writeFileSync(join(obj, 'Pins.generated.cs'), `// Generated by scripts/installer/build-installer-windows.mjs from the committed pins and the VSIX. Do not edit.
using System;
namespace MixFpga.Setup
{
    public sealed class PinInfo
    {
        public readonly string Name; public readonly long Bytes; public readonly string Sha256;
        public PinInfo(string name, long bytes, string sha256) { Name = name; Bytes = bytes; Sha256 = sha256; }
    }
    public static class Pins
    {
        public const string Version = "${V}";
        public const string ExtensionId = "emxplore.nexysvhdl";
        public const string Vsix = "nexysvhdl-${V}-win32-x64.vsix";
        public const string Nexys = "${pins['nexys-a7-100t'].file}";
        public const string De10 = "${pins['de10-lite'].file}";
        static readonly PinInfo[] All = new PinInfo[] {
${rows.join(',\n')}
        };
        public static PinInfo Lookup(string name)
        {
            foreach (PinInfo p in All) if (string.Equals(p.Name, name, StringComparison.OrdinalIgnoreCase)) return p;
            return null;
        }
    }
}
`);

// ---- name, version and manifest shown by Windows
const numeric = (V.match(/^\d+\.\d+\.\d+/) ?? ['0.0.0'])[0] + '.0';
writeFileSync(join(obj, 'AssemblyInfo.cs'), `using System.Reflection;
[assembly: AssemblyTitle("MIX-FPGA Setup")]
[assembly: AssemblyProduct("MIX-FPGA")]
[assembly: AssemblyCompany("EMXplore")]
[assembly: AssemblyCopyright("Copyright 2026 Walid Dyab")]
[assembly: AssemblyVersion("${numeric}")]
[assembly: AssemblyFileVersion("${numeric}")]
[assembly: AssemblyInformationalVersion("${V}")]
`);
// asInvoker: the installer never asks for administrator rights (the DE10-Lite's Quartus step does that later, once, inside Visual Studio Code).
writeFileSync(join(obj, 'app.manifest'), `<?xml version="1.0" encoding="utf-8"?>
<assembly manifestVersion="1.0" xmlns="urn:schemas-microsoft-com:asm.v1">
  <trustInfo xmlns="urn:schemas-microsoft-com:asm.v3">
    <security><requestedPrivileges><requestedExecutionLevel level="asInvoker" uiAccess="false"/></requestedPrivileges></security>
  </trustInfo>
  <compatibility xmlns="urn:schemas-microsoft-com:compatibility.v1">
    <application>
      <supportedOS Id="{8e0f7a12-bfb3-4fe8-b9a5-48fd50a15a9a}"/>
    </application>
  </compatibility>
</assembly>
`);

const ico = join(obj, 'MIX-FPGA.ico');
run('powershell.exe', ['-NoProfile', '-NonInteractive', '-ExecutionPolicy', 'Bypass', '-File', join(root, 'scripts', 'launcher', 'make-icon.ps1'), '-Out', ico]);

const src = (f) => join(root, 'installer', 'windows', f);
const refs = ['System.dll', 'System.Core.dll', 'System.Windows.Forms.dll', 'System.Drawing.dll'].map((r) => `/r:${r}`);
const exe = join(out, `MIX-FPGA-${V}-Windows-x64-Setup.exe`);
run(csc, ['/nologo', '/target:winexe', '/optimize+', '/codepage:65001', '/platform:anycpu', `/out:${exe}`, `/win32icon:${ico}`, `/win32manifest:${join(obj, 'app.manifest')}`, `/resource:${src('bridge.js')},bridge.js`, ...refs, src('Core.cs'), src('Ui.cs'), src('Program.cs'), join(obj, 'Pins.generated.cs'), join(obj, 'AssemblyInfo.cs')]);
copyFileSync(src('bridge.js'), join(out, 'bridge.js'));
console.log(`${exe}\n  ${statSync(exe).size} bytes  sha256 ${sha(exe)}`);
