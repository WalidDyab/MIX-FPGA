#!/usr/bin/env node
// Derives the Toolchain 1.1 (macOS) third-party inventory from the committed 1.0 inventory (Phase 5C):
//   toolchains/mixfpga/compliance/macos-arm64.inventory.json  ->  macos-arm64-1.1.inventory.json
// The 1.0 file is never modified. Every edit below is a decision of the Phase 5B report (docs/phase5b-redistribution-report.md):
// remove the 1995 IEEE sets, VITAL, UPF and the openFPGALoader bridge bitstreams; close the items that the evidence closes;
// keep the items that need counsel open. Run `node scripts/mixfpga/derive-inventory-1.1.mjs`.
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const dir = join(repo, 'toolchains', 'mixfpga', 'compliance');
const inv = JSON.parse(await readFile(join(dir, 'macos-arm64.inventory.json'), 'utf8'));
const get = (id) => inv.components.find((c) => c.id === id) ?? (() => { throw new Error(`no component ${id}`); })();

inv.toolchainVersion = '1.1';
inv.status = 'CANDIDATE';
inv.statusReason = 'Toolchain 1.1 candidate. Complete, but not final: counsel review is pending for L3 (Yosys distributed with GPLv3 readline), L4 (provenance of the "-dirty" Yosys binary), L8 (two headers without a licence statement) and L9 (integrity check versus the right to replace LGPL/GPL components), and for confirmation that shipping the corresponding-source package with the binaries satisfies the licences. Nothing here is a legal opinion.';
inv.modifications = [
    'Removed the VHDL-87 and VHDL-93 IEEE libraries (lib/ghdl/ieee/v87, lib/ghdl/ieee/v93 and lib/ghdl/src/ieee): they contain the IEEE 1076.3-1995 numeric_bit and numeric_std sources, which may be distributed only unchanged and not sold or distributed for profit.',
    'Removed the VITAL-95 and VITAL-2000 packages (lib/ghdl/src/vital95, lib/ghdl/src/vital2000) and the UPF package (lib/ghdl/src/upf), whose licence is not established.',
    'Regenerated the GHDL 2008 and 2019 IEEE library indexes (lib/ghdl/ieee/v08/ieee-obj08.cf, lib/ghdl/ieee/v19/ieee-obj19.cf) with GHDL itself, using the upstream rules of libraries/Makefile.inc without the removed packages (scripts/toolchain/ghdl-prune.mjs); the analysis timestamps of the upstream release are kept.',
    'Removed the 111 openFPGALoader bridge bitstreams (share/openFPGALoader/spiOverJtag_*, bpiOverJtag_*): no provenance; MIX-FPGA programs SRAM only and never uses them.',
    'Added the licence texts of the libraries compiled into the yosys executable, and Lima\'s own NOTICE file, which the official Lima tarball does not contain.',
    'MIX-FPGA always runs GHDL with --std=08. A design that uses the removed packages gets a normal "unit not found" error.',
];

// --- GHDL libraries -------------------------------------------------------------------------------------------------------
inv.components = inv.components.filter((c) => !['ieee-1076-3-1995', 'vital-libraries', 'upf-library', 'ofl-bridge-bitstreams'].includes(c.id));

const ieee08 = get('ieee-2008-library');
ieee08.claims = ['lib/ghdl/src/ieee2008/**'];
ieee08.evidence = `${ieee08.evidence ?? ''} The 1.1 payload keeps only the 2008 packages (the 1995 sets that GHDL builds for VHDL-87/93 are removed).`.trim();

const compiled = get('ieee-compiled');
compiled.name = 'Compiled IEEE 2008 and 2019 library indexes (GHDL .cf files)';
compiled.license = 'derived from ieee-2008-library and synopsys-libraries (same terms apply)';
compiled.evidence = 'Regenerated by GHDL itself from the remaining sources with the upstream rules of libraries/Makefile.inc (scripts/toolchain/ghdl-prune.mjs --check reproduces them); they contain no 1995, VITAL or UPF unit.';
compiled.status = 'verified';
compiled.openItems = [];
compiled.flags = [];

const std = get('ghdl-std-library');
std.status = 'verified';
std.openItems = [];
std.flags = [];
std.evidence = `${std.evidence} GHDL's documentation for v6.0.0 (doc/licenses.rst) states that std.textio and the runtime library GRT are GPLv2 and that an executable produced by GHDL may not be distributed without the VHDL sources; MIX-FPGA runs simulations in memory and distributes no student executables. The notices tell students.`;

const gnat = get('gnat-gcc-runtime');
gnat.status = 'verified';
gnat.openItems = [];
gnat.flags = [];
gnat.evidence = `${gnat.evidence ?? ''} Build origin: GHDL v6.0.0 .github/workflows/Build-MacOS.yml builds the llvm-jit macOS-15 variant with GNAT FSF build 14.2.0-1 (alire-project/GNAT-FSF-builds) and Homebrew LLVM, matching "GNAT 14.2.0" and "Homebrew LLVM version 22.1.0" in the binary; the recipe is in the GHDL source archive.`.trim();

const ghdlProgram = get('ghdl-program');
ghdlProgram.flags = ghdlProgram.flags.filter((f) => f !== 'L6');
ghdlProgram.openItems = [];
get('ghdl-libs').flags = get('ghdl-libs').flags.filter((f) => f !== 'L6');
get('libusb').flags = get('libusb').flags.filter((f) => f !== 'L5');

// --- Yosys ----------------------------------------------------------------------------------------------------------------
const ys = get('yosys-program');
ys.openItems = ['The version string ends in "-dirty". The build recipe in the source package (YosysHQ/oss-cad-suite-build ac8c7dba, default/scripts/yosys.sh) builds Yosys at origin/main on macOS and runs `sed -i` on the tracked Makefile (compiler substitution), which explains the suffix without source changes. This is an explanation, not a reproduced build; counsel and the project owner decide whether it is accepted (L4).'];
const lib = get('yosys-embedded-libs');
lib.name = 'Libraries compiled into the yosys executable';
lib.license = 'ISC (ezSAT, subcircuit); MIT (MiniSat, json11, fstapi, cxxopts); public domain (sha1, BigInteger); Berkeley (ABC)';
lib.status = 'verified';
lib.openItems = [];
lib.evidence = 'Identified from the Yosys source tree at 66306a8ca34cb1dcdafe12a5838fa8f0c1a7f4c2 (libs/ and the abc submodule b4a657e75b16b68c514a7326642ea074f8460939); the licence texts and headers are shipped.';
lib.obligation = { class: 'permissive', licenseText: true, notice: true, source: 'corresponding-source (part of the Yosys source archives)' };
const y = (f) => `repo:toolchains/mixfpga/compliance/yosys-libs/${f}`;
lib.licenseTexts = [
    { dest: 'yosys-libs/minisat-LICENSE.txt', from: y('minisat-LICENSE.txt') },
    { dest: 'yosys-libs/cxxopts-LICENSE.txt', from: y('cxxopts-LICENSE.txt') },
    { dest: 'yosys-libs/abc-copyright.txt', from: y('abc-copyright.txt') },
    { dest: 'yosys-libs/json11-license-header.txt', from: y('json11-license-header.txt') },
    { dest: 'yosys-libs/fstapi-license-header.txt', from: y('fstapi-license-header.txt') },
    { dest: 'yosys-libs/ezsat-license-header.txt', from: y('ezsat-license-header.txt') },
    { dest: 'yosys-libs/subcircuit-license-header.txt', from: y('subcircuit-license-header.txt') },
    { dest: 'yosys-libs/sha1-public-domain-note.txt', from: y('sha1-public-domain-note.txt') },
    { dest: 'yosys-libs/bigint-public-domain-note.txt', from: y('bigint-public-domain-note.txt') },
];
lib.flags = lib.flags.filter((f) => f !== 'L4');

// --- Lima -----------------------------------------------------------------------------------------------------------------
const lima = get('lima-program');
lima.licenseTexts = [...lima.licenseTexts, { dest: 'lima/NOTICE', from: 'repo:toolchains/mixfpga/compliance/upstream-notices/Lima-2.2.1-NOTICE.txt', note: 'Lima v2.2.1 NOTICE (Apache-2.0 section 4(d)); not part of the official tarball' }];
const limaGo = get('lima-go-dependencies');
limaGo.openItems = ['github.com/hashicorp/hcl/v2 v2.24.0 is MPL-2.0 and unmodified: its Source Code Form is the Go module archive in the corresponding-source package (sha256 53fd4e96ac9c190e192759daf49b63397865214d337ab5f6dbf6e68c1b0f4810).'];
limaGo.status = 'verified';

// --- Legal flags ----------------------------------------------------------------------------------------------------------
const resolve_ = (id, resolution) => {
    const f = inv.legalFlags.find((x) => x.id === id);
    if (!f) throw new Error(`no flag ${id}`);
    f.status = 'resolved';
    f.resolution = resolution;
};
resolve_('L1', 'Removed in Toolchain 1.1: the VHDL-87/93 IEEE libraries (with the IEEE 1076.3-1995 numeric_bit/numeric_std packages) are no longer shipped. MIX-FPGA runs only --std=08.');
resolve_('L2', 'Removed in Toolchain 1.1: VITAL-95, VITAL-2000 and UPF are no longer shipped; the 2008/2019 library indexes were regenerated without them.');
resolve_('L5', 'LICENSES/libusb/COPYING (LGPL-2.1) is shipped next to the 1.0.24-revision LICENSE.libusb; the 1.0.26 source is in the source package.');
resolve_('L6', 'The GHDL build recipe (.github/workflows/Build-MacOS.yml, Pipeline.yml) is in the GHDL source archive: llvm-jit, macOS 15, GNAT FSF 14.2.0-1, Homebrew LLVM.');
resolve_('L7', 'GHDL v6.0.0 doc/licenses.rst: GRT and std.textio are GPLv2; executables produced by GHDL need the VHDL sources. MIX-FPGA runs in memory and distributes no student executables; the notices tell students.');
resolve_('L10', 'Removed in Toolchain 1.1: the 111 openFPGALoader bridge bitstreams are no longer shipped.');
resolve_('L11', 'Lima NOTICE is shipped under LICENSES/lima/; the MPL-2.0 hcl module source is in the corresponding-source package.');
const open = (id, detail) => { const f = inv.legalFlags.find((x) => x.id === id); f.detail = detail; };
open('L3', 'The yosys executable loads libreadline.8.2.dylib (GPL-3.0-or-later, shipped beside it). MIX-FPGA treats the pair as a GPLv3 combination (Yosys is ISC, which is GPL-compatible), ships the GPLv3 text and provides the complete corresponding source of both (Yosys with abc and cxxopts, readline 8.2 with patch 001 and the MacPorts recipe, the build scripts) in the source package. Counsel must confirm the combined-work position.');
open('L4', 'See yosys-program: the "-dirty" suffix is explained by the build recipe; the libraries compiled into the binary are now identified and their texts shipped. Counsel and the project owner decide whether the explanation is accepted without a reproduced build.');
open('L9', 'libusb, libftdi1 and libghw (LGPL) and readline (GPLv3) are separate replaceable files. The installed toolchain is read-only by default and the integrity check reports a replaced file as "changed" (Setup page, Verify); Repair restores the original only when the student chooses Repair, nothing is restored automatically and the tools keep running with replaced files (tested in Phase 5B). The notices explain how to replace a library. Counsel must confirm this satisfies the LGPL/GPL replacement rights.');

inv.sourceOffer = {
    status: 'No written offer: the complete corresponding-source package MIX-FPGA-DE10-Lite-Support-1.1-Sources accompanies the binaries at the same place and time, and the notices say where it is. Counsel to confirm that this satisfies the licences involved.',
    mustProvideForRelease: [
        'GHDL 6.0.0 source at e589c698c351369ac5bcfe7abe1f1152ac5d4727 (ghdl-6.0.0.tar.gz) with its libraries, scripts and CI build recipe.',
        'Yosys source at 66306a8ca34cb1dcdafe12a5838fa8f0c1a7f4c2 with its abc and cxxopts submodules, and the YosysHQ build recipe (oss-cad-suite-build ac8c7dba).',
        'GNU Readline 8.2 plus patch 001 and the MacPorts port recipe (556ec864a7d9).',
        'libusb 1.0.26 and libftdi1 1.5 with their MacPorts port recipes, so the LGPL libraries can be rebuilt and replaced.',
        'The Go module archive of github.com/hashicorp/hcl/v2 v2.24.0 (MPL-2.0) compiled into Lima.',
    ],
    notRequired: inv.sourceOffer.notRequired,
};

await writeFile(join(dir, 'macos-arm64-1.1.inventory.json'), `${JSON.stringify(inv, null, 2)}\n`);
console.log(`macos-arm64-1.1.inventory.json: ${inv.components.length} components, ${inv.legalFlags.filter((f) => f.status !== 'resolved').length} open flags (${inv.legalFlags.filter((f) => f.status !== 'resolved').map((f) => f.id).join(', ')})`);
