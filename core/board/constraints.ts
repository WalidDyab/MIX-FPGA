import { type Diagnostic, errorDiag } from '../results/diagnostic';
import { type BoardDefinition, findResource } from './types';

/** Top-level port name -> board resource id (e.g. `clk100mhz` -> `CLK100MHZ`). */
export type PinMapping = Readonly<Record<string, string>>;

export interface ConstraintResult {
    /** XDC text; empty when diagnostics contain errors. */
    readonly xdc: string;
    readonly diagnostics: readonly Diagnostic[];
}

const PORT_NAME = /^[A-Za-z][A-Za-z0-9_]*$/;

function formatPeriodNs(frequencyHz: number): string {
    return (1e9 / frequencyHz).toFixed(2);
}

/**
 * Generates XDC from board data and a project's pin mapping. Pure function.
 *
 * Emits `[get_ports {name}]` with no spaces inside the braces: Phase 2 showed
 * nextpnr-xilinx only matches that form. Bus resources map to `name[i]`.
 */
export function generateXdc(board: BoardDefinition, pins: PinMapping): ConstraintResult {
    const diagnostics: Diagnostic[] = [];
    const lines: string[] = [`## Generated by NexysVHDL for ${board.name}. Do not edit.`];

    for (const port of Object.keys(pins).sort()) {
        const resourceId = pins[port]!;
        if (!PORT_NAME.test(port)) {
            diagnostics.push(errorDiag('board', 'PIN_PORT_INVALID', `"${port}" is not a valid top-level port name`));
            continue;
        }
        const resource = findResource(board, resourceId);
        if (!resource) {
            diagnostics.push(
                errorDiag('board', 'PIN_RESOURCE_UNKNOWN', `port "${port}" maps to "${resourceId}", which ${board.name} does not define`),
            );
            continue;
        }

        lines.push('', `## ${port} -> ${resource.id}${resource.description ? ` (${resource.description})` : ''}`);
        const targets = resource.pins.length === 1 ? [port] : resource.pins.map((_, i) => `${port}[${i}]`);
        resource.pins.forEach((pin, i) => {
            lines.push(`set_property -dict { PACKAGE_PIN ${pin} IOSTANDARD ${resource.ioStandard} } [get_ports {${targets[i]}}]`);
        });
        if (resource.clock) {
            const period = formatPeriodNs(resource.clock.frequencyHz);
            lines.push(`create_clock -name ${port} -period ${period} [get_ports {${port}}]`);
        }
    }

    const mapped = Object.values(pins);
    for (const dup of new Set(mapped.filter((id, i) => mapped.indexOf(id) !== i))) {
        diagnostics.push(errorDiag('board', 'PIN_RESOURCE_REUSED', `board resource "${dup}" is mapped to more than one port`));
    }

    return { xdc: diagnostics.length > 0 ? '' : lines.join('\n') + '\n', diagnostics };
}
