import { readFile, stat, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { type ToolRunner, succeeded } from '../../process/tool-runner';
import type { BuildArtifact } from '../../results/artifact';
import { type Diagnostic, errorDiag, type LogRef } from '../../results/diagnostic';
import { sha256File } from '../../util/hash';
import { applyDeviceCapacity } from '../capacity';
import type { ImplementationProvider, ImplementationRequest, ImplementationResult, ImplementationStage, ResourceUtilization } from '../types';
import { apioReachedStage, apioStageTracker, countPrimitives, parseApioBuildLog, parseNextpnrReport, summarizeTiming } from './reports';

const BUILD_TIMEOUT_MS = 15 * 60_000;

/** Names of the files staged for Apio. Nothing else is placed in the staging directory. */
export const STAGED = { verilog: 'generated.v', xdc: 'generated.xdc', ini: 'apio.ini' } as const;

/** Apio's output locations relative to the staging directory. */
const OUT = { dir: join('_build', 'default'), bit: 'hardware.bit', pnr: 'hardware.pnr', json: 'hardware.json' } as const;

/** Where Apio leaves the canonical bitstream inside a staging directory. */
export function apioBitstreamPath(stagingDir: string): string {
    return join(stagingDir, OUT.dir, OUT.bit);
}

/** apio.ini owned by NexysVHDL; students never edit it. */
export function renderApioIni(apioBoard: string, topModule: string): string {
    return [
        '; Generated by NexysVHDL. Do not edit.',
        '[env:default]',
        `board = ${apioBoard}`,
        `top-module = ${topModule}`,
        `constraint-file = ${STAGED.xdc}`,
        '',
    ].join('\n');
}

/**
 * ImplementationProvider backed by Apio (Yosys -> nextpnr-xilinx -> Project X-Ray).
 * Platform-neutral: needs only the Apio executable path. Runs `apio build`
 * inside the isolated staging directory (ADR-001).
 */
export class ApioImplementationProvider implements ImplementationProvider {
    readonly id = 'apio';

    constructor(
        private readonly apio: string,
        private readonly runner: ToolRunner,
    ) {}

    async implement(req: ImplementationRequest): Promise<ImplementationResult> {
        const started = Date.now();
        const logs: LogRef[] = [];
        let reachedStage: ImplementationStage | undefined;
        const fail = (diagnostics: Diagnostic[], stagedFiles: readonly string[] = []): ImplementationResult => ({
            status: 'failed', diagnostics, logs, stagedFiles, durationMs: Date.now() - started,
            ...(reachedStage ? { reachedStage } : {}),
        });

        const apioBoard = req.board.backendIds['apio'];
        if (!apioBoard) {
            return fail([errorDiag('implementation', 'APIO_BOARD_UNKNOWN', `Board "${req.board.id}" has no Apio board id.`)]);
        }

        // GHDL emits lower-case module names; VHDL identifiers are case-insensitive.
        const top = req.project.config.top.toLowerCase();
        const staged = await req.workspace.stageImplementation([
            { name: STAGED.verilog, sourcePath: req.verilog.path },
            { name: STAGED.xdc, content: req.xdc },
            { name: STAGED.ini, content: renderApioIni(apioBoard, top) },
        ]);

        const run = await this.runner.run({
            executable: this.apio,
            args: ['build', '--verbose'],
            cwd: staged.dir,
            timeoutMs: BUILD_TIMEOUT_MS,
            ...(req.signal ? { signal: req.signal } : {}),
            ...(req.onStage ? { onOutput: apioStageTracker(req.onStage) } : {}),
        });
        const logText = `${run.stdout}\n${run.stderr}`;
        const logPath = join(req.workspace.paths.logs, 'apio-build.log');
        await writeFile(logPath, logText, 'utf8');
        logs.push({ label: 'apio-build', path: logPath });
        reachedStage = apioReachedStage(logText);

        if (run.outcome === 'spawn-failed') {
            return fail([errorDiag('implementation', 'APIO_NOT_STARTED', `Could not start Apio (${this.apio}): ${run.errorMessage ?? 'unknown error'}`)], staged.files);
        }
        const facts = parseApioBuildLog(logText);
        const diagnostics: Diagnostic[] = [...facts.diagnostics];
        if (run.outcome !== 'exited') {
            diagnostics.push(errorDiag('implementation', 'APIO_' + run.outcome.toUpperCase().replace('-', '_'), `Apio build ${run.outcome}.`));
            return fail(diagnostics, staged.files);
        }
        if (!succeeded(run)) {
            if (!diagnostics.some((d) => d.severity === 'error')) {
                diagnostics.push(errorDiag('implementation', 'APIO_BUILD_FAILED', `apio build exited with code ${run.exitCode}.`));
            }
            return fail(diagnostics, staged.files);
        }

        const outDir = join(staged.dir, OUT.dir);
        const bitPath = apioBitstreamPath(staged.dir);
        let bitstream: BuildArtifact;
        try {
            const s = await stat(bitPath);
            if (s.size === 0) throw new Error('empty');
            bitstream = { kind: 'bitstream', path: bitPath, canonical: true, sizeBytes: s.size, sha256: await sha256File(bitPath) };
        } catch {
            diagnostics.push(errorDiag('implementation', 'APIO_NO_BITSTREAM', `Apio reported success but ${bitPath} is missing or empty.`));
            return fail(diagnostics, staged.files);
        }

        let utilization: ResourceUtilization | undefined;
        let clocks = facts.maxFrequency;
        try {
            const report = parseNextpnrReport(await readFile(join(outDir, OUT.pnr), 'utf8'));
            // Capacities as the data sheet counts them (nextpnr's own bel/pad counts stay in `device`).
            utilization = req.board.fpga.capacity ? applyDeviceCapacity(report.utilization, req.board.fpga.capacity) : report.utilization;
            if (report.clocks.length > 0) clocks = report.clocks;
        } catch {
            diagnostics.push({ severity: 'warning', source: 'implementation', code: 'APIO_NO_PNR_REPORT', message: 'nextpnr report not found; utilization unavailable.' });
        }
        try {
            const primitives = countPrimitives(await readFile(join(outDir, OUT.json), 'utf8'), top);
            utilization = { ...(utilization ?? {}), primitives };
        } catch {
            /* primitive counts are optional detail */
        }

        return {
            status: 'succeeded',
            bitstream,
            timing: summarizeTiming(clocks, facts),
            stagedFiles: staged.files,
            diagnostics,
            logs,
            durationMs: Date.now() - started,
            ...(reachedStage ? { reachedStage } : {}),
            ...(facts.part !== undefined ? { part: facts.part } : {}),
            ...(utilization ? { utilization } : {}),
        };
    }
}
